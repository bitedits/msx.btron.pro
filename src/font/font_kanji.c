void font_kanji_init(void)
{
    /* Test for Kanji ROM presence */
    msx_out(PORT_KANJI_ADDR_LO, 0x00);
    msx_out(PORT_KANJI_ADDR_HI, 0x00);
    uint8_t d1 = msx_in(PORT_KANJI_DATA_L1);
    uint8_t d2 = msx_in(PORT_KANJI_DATA_L1);
    /* If data changes or is not 0xFF, Kanji ROM is likely present */
    s_has_kanji_rom = (d1 != 0xFF || d2 != 0xFF);
}

bool font_has_kanji_rom(void)
{
    return s_has_kanji_rom;
}

void font_draw_kanji(uint16_t x, uint16_t y, uint16_t jis_or_id, uint8_t fg_col, uint8_t bg_col)
{
    if (x + 16 > SCREEN_WIDTH || y + 16 > SCREEN_HEIGHT) return;

    const uint8_t *bitmap = NULL;
    uint8_t rom_buf[32];

    /* Check embedded table first */
    for (uint8_t i = 0; i < sizeof(s_embedded_kanji)/sizeof(s_embedded_kanji[0]); i++) {
        if (s_embedded_kanji[i].id == jis_or_id) {
            bitmap = s_embedded_kanji[i].bitmap;
            break;
        }
    }

    /* Fallback to Kanji ROM if present and not in embedded table */
    if (!bitmap && s_has_kanji_rom && jis_or_id > 0xFF) {
        msx_out(PORT_KANJI_ADDR_LO, (uint8_t)(jis_or_id & 0xFF));
        msx_out(PORT_KANJI_ADDR_HI, (uint8_t)((jis_or_id >> 8) & 0xFF));
        for (uint8_t b = 0; b < 32; b++) {
            rom_buf[b] = msx_in(PORT_KANJI_DATA_L1);
        }
        bitmap = rom_buf;
    }

    if (!bitmap) {
        /* Default to first embedded glyph if not found */
        bitmap = s_embedded_kanji[0].bitmap;
    }

    uint8_t byte_x = (uint8_t)(x >> 1);
    uint16_t eff_y = y + vdp_get_draw_y_offset();
    uint8_t pair[4];
    pair[0] = (uint8_t)((bg_col << 4) | (bg_col & 0x0F));
    pair[1] = (uint8_t)((bg_col << 4) | (fg_col & 0x0F));
    pair[2] = (uint8_t)((fg_col << 4) | (bg_col & 0x0F));
    pair[3] = (uint8_t)((fg_col << 4) | (fg_col & 0x0F));

    /* Render 16 rows * 16 pixels = 8 bytes per row */
    for (uint8_t row = 0; row < 16; row++) {
        uint8_t b0 = bitmap[row * 2];
        uint8_t b1 = bitmap[row * 2 + 1];
        vdp_set_vram_write_line(byte_x, eff_y + row);

        /* First 8 pixels from b0 (4 VRAM bytes) */
        msx_out(PORT_VDP_DATA, pair[b0 >> 6]);
        msx_out(PORT_VDP_DATA, pair[(b0 >> 4) & 3]);
        msx_out(PORT_VDP_DATA, pair[(b0 >> 2) & 3]);
        msx_out(PORT_VDP_DATA, pair[b0 & 3]);

        /* Next 8 pixels from b1 (4 VRAM bytes) */
        msx_out(PORT_VDP_DATA, pair[b1 >> 6]);
        msx_out(PORT_VDP_DATA, pair[(b1 >> 4) & 3]);
        msx_out(PORT_VDP_DATA, pair[(b1 >> 2) & 3]);
        msx_out(PORT_VDP_DATA, pair[b1 & 3]);
    }
}
