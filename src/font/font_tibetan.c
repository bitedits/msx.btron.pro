const uint8_t *font_tibetan_get_glyph8x16(uint16_t codepoint)
{
    for (uint16_t i = 0; g_tibetan_8x16[i].codepoint != 0; i++) {
        if (g_tibetan_8x16[i].codepoint == codepoint) {
            return g_tibetan_8x16[i].bitmap;
        }
    }
    return NULL;
}

const uint8_t *font_tibetan_get_glyph16x16(uint16_t codepoint)
{
    for (uint16_t i = 0; g_tibetan_16x16[i].codepoint != 0; i++) {
        if (g_tibetan_16x16[i].codepoint == codepoint) {
            return g_tibetan_16x16[i].bitmap;
        }
    }
    return NULL;
}

void font_draw_tibetan_glyph(uint16_t x, uint16_t y, uint16_t codepoint, uint8_t fg_col, uint8_t bg_col)
{
    if (x + 8 > SCREEN_WIDTH || y + 16 > SCREEN_HEIGHT) return;

    /* Check 8x16 table */
    const uint8_t *bmp8 = font_tibetan_get_glyph8x16(codepoint);
    if (bmp8) {
        uint16_t byte_x = x / 2;
        for (uint8_t row = 0; row < 16; row++) {
            uint8_t bits = bmp8[row];
            uint32_t addr = ((uint32_t)(y + row) * 256) + byte_x;
            vdp_set_vram_write_addr(addr);

            for (uint8_t col = 0; col < 4; col++) {
                uint8_t p0 = (bits & 0x80) ? fg_col : bg_col;
                bits <<= 1;
                uint8_t p1 = (bits & 0x80) ? fg_col : bg_col;
                bits <<= 1;
                msx_out(PORT_VDP_DATA, (uint8_t)((p0 << 4) | (p1 & 0x0F)));
            }
        }
        return;
    }

    /* Check 16x16 table */
    const uint8_t *bmp16 = font_tibetan_get_glyph16x16(codepoint);
    if (bmp16 && x + 16 <= SCREEN_WIDTH) {
        uint16_t byte_x = x / 2;
        for (uint8_t row = 0; row < 16; row++) {
            uint8_t b0 = bmp16[row * 2];
            uint8_t b1 = bmp16[row * 2 + 1];
            uint32_t addr = ((uint32_t)(y + row) * 256) + byte_x;
            vdp_set_vram_write_addr(addr);

            for (uint8_t col = 0; col < 4; col++) {
                uint8_t p0 = (b0 & 0x80) ? fg_col : bg_col;
                b0 <<= 1;
                uint8_t p1 = (b0 & 0x80) ? fg_col : bg_col;
                b0 <<= 1;
                msx_out(PORT_VDP_DATA, (uint8_t)((p0 << 4) | (p1 & 0x0F)));
            }
            for (uint8_t col = 0; col < 4; col++) {
                uint8_t p0 = (b1 & 0x80) ? fg_col : bg_col;
                b1 <<= 1;
                uint8_t p1 = (b1 & 0x80) ? fg_col : bg_col;
                b1 <<= 1;
                msx_out(PORT_VDP_DATA, (uint8_t)((p0 << 4) | (p1 & 0x0F)));
            }
        }
    }
}

uint16_t font_render_tibetan_utf8(uint16_t x, uint16_t y, const char *utf8_str, uint8_t fg_col, uint8_t bg_col)
{
    if (!utf8_str) return 0;

    uint16_t cur_x = x;
    const uint8_t *p = (const uint8_t *)utf8_str;

    while (*p) {
        uint16_t cp = 0;
        if ((*p & 0x80) == 0) {
            /* 1-byte ASCII */
            if (*p == ' ') {
                cur_x += 6;
            } else if (*p == '\n') {
                cur_x = x;
                y += 18;
            }
            p++;
            continue;
        } else if ((*p & 0xE0) == 0xC0) {
            /* 2-byte UTF-8 */
            cp = (uint16_t)(((*p & 0x1F) << 6) | (*(p + 1) & 0x3F));
            p += 2;
        } else if ((*p & 0xF0) == 0xE0) {
            /* 3-byte UTF-8 (Tibetan U+0F00..U+0FFF is in this range: 0xE0 0xBC..0xBF) */
            cp = (uint16_t)(((*p & 0x0F) << 12) | ((*(p + 1) & 0x3F) << 6) | (*(p + 2) & 0x3F));
            p += 3;
        } else {
            p++;
            continue;
        }

        if (cp >= 0x0F00 && cp <= 0x0FFF) {
            /* Check if this is a subjoined consonant or vowel that stacks on previous */
            font_draw_tibetan_glyph(cur_x, y, cp, fg_col, bg_col);
            /* Advancing width: Tsheg (0x0F0B) is 4px, Shad (0x0F0D) is 6px, letters are 8px */
            if (cp == 0x0F0B) cur_x += 4;
            else if (cp == 0x0F0D) cur_x += 6;
            else if (cp >= 0x0F71 && cp <= 0x0F84) {
                /* Vowels: overlay on preceding consonant, do not advance cursor */
            } else if (cp >= 0x0F90 && cp <= 0x0FBC) {
                /* Subjoined consonants: overlay on preceding consonant, do not advance cursor */
            } else {
                cur_x += 8;
            }

            if (cur_x + 8 > SCREEN_WIDTH) {
                cur_x = x;
                y += 18;
            }
        }
    }

    return cur_x - x;
}
